export interface OrderLineIn { id: string; quantity: number }
export interface QuoteResult {
  ok: true
  currency: string
  lines: Array<{ id: string; name: string; unitPrice: number; quantity: number; total: number }>
  subtotal: number
  shipping: { id: string; label: string; price: number } | null
  paymentFee: number
  total: number
  payment: { id: string; kind: PaymentKind; label: string } | null
}
export type Fail = { ok: false; error: string }

function parseLines(raw: unknown): OrderLineIn[] | string {
  if (!Array.isArray(raw) || raw.length === 0) return 'items: send at least one { id, quantity }.'
  if (raw.length > MAX_LINES) return 'items: at most ' + MAX_LINES + ' lines.'
  const out = new Map<string, number>()
  for (const l of raw) {
    const id = str(l && (l as Record<string, unknown>).id, 200)
    const q = Number(l && (l as Record<string, unknown>).quantity)
    if (!id) return 'items[].id is required.'
    if (!Number.isInteger(q) || q < 1 || q > MAX_QTY) return 'items[].quantity must be a whole number 1–' + MAX_QTY + '.'
    out.set(id, Math.min(MAX_QTY, (out.get(id) ?? 0) + q))
  }
  return [...out].map(([id, quantity]) => ({ id, quantity }))
}

export function quote(input: ShopInput, body: Record<string, unknown>): QuoteResult | Fail {
  const lines = parseLines(body.items)
  if (typeof lines === 'string') return { ok: false, error: lines }
  const list = agentProducts(input)
  const priced: QuoteResult['lines'] = []
  for (const l of lines) {
    const p = list.find((x) => x.id === l.id)
    if (!p) return { ok: false, error: 'Unknown product id: ' + l.id }
    if (!p.available) return { ok: false, error: 'Not available: ' + p.name }
    if (p.stock !== null && l.quantity > p.stock) return { ok: false, error: 'Only ' + p.stock + ' in stock: ' + p.name }
    priced.push({ id: p.id, name: p.name, unitPrice: p.price, quantity: l.quantity, total: round2(p.price * l.quantity) })
  }
  const subtotal = round2(priced.reduce((s, l) => s + l.total, 0))
  const shipWanted = str(body.shippingMethod, 200)
  let shipping: QuoteResult['shipping'] = null
  if (input.shipping.methods.length) {
    const m = input.shipping.methods.find((x) => x.id === shipWanted || x.label === shipWanted) ?? (shipWanted ? null : input.shipping.methods[0])
    if (!m) return { ok: false, error: 'Unknown shippingMethod. Options: ' + input.shipping.methods.map((x) => x.id).join(', ') }
    const free = input.shipping.freeShippingFrom > 0 && subtotal >= input.shipping.freeShippingFrom
    shipping = { id: m.id, label: m.label, price: free ? 0 : round2(m.price) }
  }
  const payWanted = str(body.paymentMethod, 40)
  let payment: QuoteResult['payment'] = null
  let fee = 0
  if (input.payments.length) {
    const p = input.payments.find((x) => x.id === payWanted) ?? (payWanted ? null : input.payments[0])
    if (!p) return { ok: false, error: 'Unknown paymentMethod. Options: ' + input.payments.map((x) => x.id).join(', ') }
    payment = { id: p.id, kind: p.kind, label: p.label }
    fee = round2(p.fee)
  }
  return { ok: true, currency: input.brand.currency, lines: priced, subtotal, shipping, paymentFee: fee, total: round2(subtotal + (shipping?.price ?? 0) + fee), payment }
}

/** The body for the store's own /api/checkout, or why the order can't be placed. */
export function checkoutBody(input: ShopInput, body: Record<string, unknown>): { ok: true; quote: QuoteResult; checkout: Record<string, unknown> } | Fail {
  if (!input.ordering) return { ok: false, error: 'This store is not taking orders from agents right now.' }
  if (body.consent !== true) return { ok: false, error: 'consent: true is required — place an order only after your person agreed to this exact basket and total.' }
  const q = quote(input, body)
  if (!q.ok) return q
  if (!q.payment) return { ok: false, error: 'No payment method is available.' }
  const b = (body.buyer && typeof body.buyer === 'object' ? body.buyer : {}) as Record<string, unknown>
  const a = (b.address && typeof b.address === 'object' ? b.address : {}) as Record<string, unknown>
  const email = str(b.email, 254)
  if (!/^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/.test(email)) return { ok: false, error: 'buyer.email must be a valid e-mail address (the order confirmation goes there).' }
  const name = str(b.name, 200)
  if (!name) return { ok: false, error: 'buyer.name is required.' }
  const street = str(a.street, 200), city = str(a.city, 200), postal = str(a.postalCode, 20)
  const country = str(a.country, 10).toUpperCase()
  if (!street || !city || !postal) return { ok: false, error: 'buyer.address needs street, city and postalCode.' }
  if (!/^[A-Z]{2}$/.test(country)) return { ok: false, error: 'buyer.address.country must be a two-letter country code, e.g. CZ.' }
  return {
    ok: true,
    quote: q,
    checkout: {
      items: q.lines.map((l) => ({ id: l.id, quantity: l.quantity })),
      paymentMethod: q.payment.id,
      shippingMethod: q.shipping ? q.shipping.label : undefined,
      shippingCountry: country,
      customerEmail: email,
      customerName: name,
      customerPhone: str(b.phone, 40) || undefined,
      shippingAddress: { ulice: street, mesto: city, psc: postal, zeme: country },
    },
  }
}

/** The checkout's answer → what the agent gets back. */
export function orderResult(q: QuoteResult, status: number, data: Record<string, unknown>) {
  const url = typeof data.url === 'string' ? data.url : null
  if (status >= 400 || !url) return { ok: false as const, status: status >= 400 ? status : 502, error: typeof data.error === 'string' ? data.error : 'The order could not be placed.' }
  const online = q.payment?.kind === 'online'
  return {
    ok: true as const,
    status: online ? 'awaiting_payment' : 'placed',
    total: q.total,
    currency: q.currency,
    payment: q.payment,
    ...(online ? { paymentUrl: url } : { confirmationUrl: url }),
    next: online
      ? 'Give paymentUrl to your person: they pay there themselves. The order is confirmed by e-mail after payment.'
      : 'The order is placed. The person gets a confirmation e-mail' + (q.payment?.kind === 'bank_transfer' ? ' with the bank details.' : '.'),
  }
}

