// Agent-ready store (2026-11-06): the files every generated store carries so AI agents can read
// its catalog and buy from it — the open "agent-shop" format, version 1 (docs/agents/agent-shop.md).
//
//   /.well-known/agent-shop.json   → app/api/agent/shop      the store described for agents
//   /llms.txt                      → app/api/agent/llms      the same as Markdown
//   GET  /api/agent/products?q=    the catalog (search, one product by id or slug)
//   POST /api/agent/quote          prices a basket (shipping + fees), changes nothing
//   POST /api/agent/order          places the order through the store's own /api/checkout
//   POST /api/mcp                  the same as an MCP server (Streamable HTTP, stateless JSON)
//
// All LOCKED (PLATFORM_LOCKED_FILES): the AI never writes them. White-label: nothing here names
// the platform. The pure part (lib/agent-shop.ts) has no imports, so __tests__/agent-shops.test.mjs
// loads it straight from this string. Prices are never taken from an agent: a quote is computed
// from the store's own catalog and the order goes through /api/checkout, which re-prices it again
// (and in hosted mode the platform re-prices it a third time). Stock, shipping and payment methods
// come from the platform (/api/store/agent) in hosted mode, from local fallbacks when self-hosted.
//
// The sources are String.raw literals: they must not contain a backtick or a dollar-brace.

