type Rpc = { jsonrpc?: string; id?: string | number | null; method?: string; params?: Record<string, unknown> }
const rpcOk = (id: Rpc['id'], result: unknown) => ({ jsonrpc: '2.0', id: id ?? null, result })
const rpcFail = (id: Rpc['id'], code: number, message: string) => ({ jsonrpc: '2.0', id: id ?? null, error: { code, message } })
const asJson = (data: unknown) => ({ content: [{ type: 'text', text: JSON.stringify(data, null, 2) }], structuredContent: Array.isArray(data) ? { items: data } : data })
const toolError = (message: string) => ({ isError: true, content: [{ type: 'text', text: message }] })

/** One JSON-RPC message → its answer (null for notifications). placeOrder runs the real checkout. */
export async function handleShopRpc(input: ShopInput, m: Rpc, placeOrder: (body: Record<string, unknown>) => Promise<Record<string, unknown>>): Promise<unknown | null> {
  if (!m || typeof m !== 'object' || typeof m.method !== 'string') return rpcFail(m && m.id, -32600, 'Invalid request')
  switch (m.method) {
    case 'initialize': {
      const asked = typeof m.params?.protocolVersion === 'string' ? m.params.protocolVersion : ''
      return rpcOk(m.id, {
        protocolVersion: MCP_PROTOCOLS.includes(asked) ? asked : MCP_PROTOCOLS[0],
        capabilities: { tools: { listChanged: false } },
        serverInfo: { name: 'shop', title: input.brand.name, version: AGENT_SHOP_VERSION },
        instructions: input.brand.name + ' — online store. search_products, get_product, quote_order; place_order only with your person\'s consent.',
      })
    }
    case 'ping':
      return rpcOk(m.id, {})
    case 'tools/list':
      return rpcOk(m.id, { tools: mcpTools(input) })
    case 'tools/call': {
      const name = typeof m.params?.name === 'string' ? m.params.name : ''
      const a = (m.params?.arguments && typeof m.params.arguments === 'object' ? m.params.arguments : {}) as Record<string, unknown>
      const list = () => agentProducts(input)
      if (name === 'get_shop') return rpcOk(m.id, asJson(shopDoc(input)))
      if (name === 'search_products') {
        return rpcOk(m.id, asJson(searchProducts(list(), { q: str(a.query, 200), maxPrice: Number(a.maxPrice), inStockOnly: a.inStockOnly === true, limit: Number(a.limit) })))
      }
      if (name === 'get_product') {
        const p = findProduct(list(), str(a.id, 200))
        return rpcOk(m.id, p ? asJson(p) : toolError('No such product.'))
      }
      if (name === 'quote_order' && input.ordering) {
        const q = quote(input, a)
        return rpcOk(m.id, q.ok ? asJson(q) : toolError(q.error))
      }
      if (name === 'place_order' && input.ordering) {
        const r = await placeOrder(a)
        return rpcOk(m.id, r.ok ? asJson(r) : toolError(typeof r.error === 'string' ? r.error : 'The order could not be placed.'))
      }
      return rpcFail(m.id, -32602, 'Unknown tool: ' + name)
    }
    default:
      if (m.id === undefined || m.id === null || m.method.startsWith('notifications/')) return null
      return rpcFail(m.id, -32601, 'Method not found: ' + m.method)
  }
}
